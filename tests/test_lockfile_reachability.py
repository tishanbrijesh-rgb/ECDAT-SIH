    # ------------------------------------------------------------------
    # Malformed and negative cases
    # ------------------------------------------------------------------
    def test_malformed_package_lock_counts_as_failure_not_finding(self):
        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "package-lock.json").write_text("not valid json {{{")
            evidence, metrics = scan_with_metrics(directory)

        self.assertEqual(metrics["in_scope_files"], 1)
        self.assertEqual(metrics["failed_files"], 1)
        self.assertEqual(metrics["scanned_files"], 0)
        self.assertEqual(metrics["coverage_pct"], 0.0)
        self.assertFalse(any(item.get("source") == "dep" for items in evidence.values() for item in items))

    def test_empty_gemfile_lock_produces_no_findings_but_counts_as_scanned(self):
        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "Gemfile.lock").write_text(
                "GEM\n  remote: https://rubygems.org/\n\nGEM\n  remote: https://rubygems.org/\n  specs:\n"
            )
            evidence, metrics = scan_with_metrics(directory)

        self.assertEqual(metrics["in_scope_files"], 1)
        self.assertEqual(metrics["scanned_files"], 1)
        self.assertEqual(metrics["failed_files"], 0)
        flat = [item for items in evidence.values() for item in items]
        dep_items = [item for item in flat if item.get("source") == "dep"]
        self.assertEqual(dep_items, [])

    def test_go_sum_without_crypto_modules_produces_no_findings(self):
        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "go.sum").write_text(
                "std stdlib go1.22\n"
                "example.com/some-lib v1.0.0 h1:abc=\n"
                "example.com/some-lib v1.0.0/go.mod h1:def=\n"
            )
            evidence, metrics = scan_with_metrics(directory)

        self.assertEqual(metrics["in_scope_files"], 1)
        self.assertEqual(metrics["scanned_files"], 1)
        flat = [item for items in evidence.values() for item in items]
        dep_items = [item for item in flat if item.get("source") == "dep"]
        self.assertEqual(dep_items, [])

