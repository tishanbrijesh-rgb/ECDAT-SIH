"""Tests that every implemented lockfile handler is reachable through scan_with_metrics().

The defect (pre-fix): handlers exist for package-lock.json, Gemfile.lock, go.sum,
and Cargo.lock in dep_collector.py, and the dispatch in main.py calls them, but
_inventory() does not place those filenames in the supported-file set. Therefore
they never execute through the main scan path.
"""
import tempfile
import unittest
from pathlib import Path

from scanner.main import scan_with_metrics

# Contents with at least one known crypto dependency per lockfile.
REQUIREMENTS_TXT = "cryptography>=41.0\n"
POM_XML = """<project xmlns="http://maven.apache.org/POM/4.0.0">
  <dependencies>
    <dependency><groupId>org.bouncycastle</groupId>
      <artifactId>bcprov-jdk18on</artifactId></dependency>
  </dependencies>
</project>"""
PACKAGE_LOCK = """{
  "lockfileVersion": "3",
  "packages": {
    "": {"name": "app", "version": "1.0.0"},
    "node_modules/crypto-js": {"version": "4.2.0"}
  }
}"""
GEMFILE_LOCK = """GEM
  remote: https://rubygems.org/
  specs:
    openssl (2.2.0)

GEM
  remote: https://rubygems.org/
  specs:
"""
GO_SUM = """\
std stdlib go1.22
golang.org/x/crypto v0.14.0 h1:wcQYHkvc2kmZftDVAa6nZb0+fVpg2Wn4ehH/Um9cFxI=
golang.org/x/crypto v0.14.0/go.mod h1:MVFd36IqK+ZRMNq4DnspNMyqU0kR+2ZAE4Q3sLb4N1M=
"""
CARGO_LOCK = """\
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "ring"
version = "0.17.8"
"""


class DependencyLockfileReachabilityTests(unittest.TestCase):
    """Each test creates a repo with one lockfile and verifies the main scan
    path processes it through the dep collector."""

    # ------------------------------------------------------------------
    # requirements.txt
    # ------------------------------------------------------------------
    def test_requirements_txt_is_reachable_and_produces_evidence(self):
        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "requirements.txt").write_text(REQUIREMENTS_TXT)
            evidence, metrics = scan_with_metrics(directory)

        self.assertEqual(metrics["in_scope_files"], 1)
        self.assertEqual(metrics["scanned_files"], 1)
        self.assertEqual(metrics["failed_files"], 0)
        self.assertEqual(metrics["coverage_pct"], 100.0)
        self.assertGreater(metrics["collector_stats"]["dep"], 0)
        flat = [item for items in evidence.values() for item in items]
        dep_items = [item for item in flat if item.get("source") == "dep"]
        self.assertTrue(dep_items, "dependency collector should produce evidence")
        algorithms = {item["algorithm"] for item in dep_items}
        self.assertTrue(algorithms & {"RSA", "AES", "ECDSA", "Ed25519", "SHA-256"})

    def test_requirements_txt_is_counted_in_total_and_supported(self):
        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "requirements.txt").write_text(REQUIREMENTS_TXT)
            (Path(directory) / "README.md").write_text("# project\n")
            _evidence, metrics = scan_with_metrics(directory)

        self.assertEqual(metrics["total_files"], 2)
        self.assertEqual(metrics["in_scope_files"], 1)

    # ------------------------------------------------------------------
    # pom.xml
